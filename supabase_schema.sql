-- VIEWS

CREATE VIEW SellerDashboard AS
SELECT
    u.name AS seller,
    COUNT(DISTINCT p.product_id) AS total_products,
    COALESCE(SUM(od.quantity * od.unit_price), 0) AS total_sales,
    COALESCE(ROUND(AVG(r.rating), 1), 0) AS avg_rating

FROM Users u

LEFT JOIN Product p
    ON u.user_id = p.seller_id

LEFT JOIN OrderDetails od
    ON p.product_id = od.product_id

LEFT JOIN Review r
    ON p.product_id = r.product_id

WHERE u.role = 'Seller'

GROUP BY u.name;

CREATE VIEW AdminOrderOverview AS
SELECT
    o.order_id,
    u.name AS customer,
    o.order_date,
    o.total_amount,
    pay.status AS payment_status,
    pay.payment_method

FROM Orders o

JOIN Users u
    ON o.customer_id = u.user_id

JOIN Payment pay
    ON o.order_id = pay.order_id;

